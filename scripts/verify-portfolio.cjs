const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
let playwright;
try { playwright = require("playwright"); }
catch { playwright = require(path.join(path.dirname(process.execPath), "../node_modules/playwright")); }
const { chromium } = playwright;
const output = path.join(os.tmpdir(), "portfolio-review");
fs.mkdirSync(output, {recursive: true});
const url = process.argv[2] || pathToFileURL(path.resolve("index.html")).href;
(async () => {
  const browser = await chromium.launch({channel: "chrome", headless: true});
  const errors = [];
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}, reducedMotion:"reduce"});
    const instagramRequests = [];
    page.on("request", request => { if (request.url().includes("instagram.com")) instagramRequests.push(request.url()); });
    await page.route("https://www.instagram.com/**", route => route.abort());
    await page.addInitScript(() => {
      window.copiedText = "";
      Object.defineProperty(navigator, "clipboard", {value: {writeText: async text => { window.copiedText = text; }}, configurable: true});
    });
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(url, {waitUntil:"load"});
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({path:path.join(output,"desktop-light.png")});
    assert.equal(await page.locator(".hero-title").innerText(), "Angelo Joe Delos Santos");
    assert.equal(await page.locator("#awsCredentialCount").innerText(), "6");
    assert.deepEqual(await page.locator("#navLinks a").evaluateAll(links=>links.map(a=>a.hash)),
      ["#engineering-focus","#about-me","#skills","#experience","#leadership","#certifications","#projects","#hiking","#contact"]);
    assert.equal(await page.locator(".exp-toggle").count(), 6);
    await page.locator(".exp-toggle").first().click();
    assert.equal(await page.locator("#experience-details-1").isVisible(), true);
    const implementations = page.locator("#experience-details-1 .client-work-card");
    assert.equal(await implementations.count(), 4);
    assert.deepEqual(await implementations.locator(":scope > span").allTextContents(),
      ["Food & retail enterprise", "Financial services / insurance", "Food & retail enterprise", "Transportation & infrastructure"]);
    assert.ok((await implementations.nth(2).innerText()).includes("Amazon SageMaker Unified Studio"));
    assert.ok((await implementations.nth(3).innerText()).includes("AWS account support & cloud provisioning"));
    await page.locator(".exp-toggle").first().click();
    assert.equal(await page.locator("#experience-details-1").isVisible(), false);
    await page.getByRole("button", {name:"Expand all companies",exact:true}).click();
    assert.equal(await page.locator(".exp-card-body:visible").count(), 6);
    await page.getByRole("button", {name:"Collapse all companies",exact:true}).click();
    assert.equal(await page.locator(".exp-card-body:visible").count(), 0);
    await page.locator('[data-cert-filter="aws"]').click();
    assert.equal(await page.locator(".cert-card:visible").count(), 6);
    const cloudOps = page.locator(".cert-card").filter({has: page.getByRole("heading", {name: "AWS Certified CloudOps Engineer - Associate", exact: true})});
    assert.equal(await cloudOps.isVisible(), true);
    assert.equal(await cloudOps.locator(".cert-dates").innerText(), "Issued Sep 22, 2026 · Expires Sep 22, 2029");
    assert.equal(await cloudOps.getByRole("link", {name: "Verify", exact: true}).getAttribute("href"), "https://www.credly.com/badges/10633a4f-6ec6-49ff-81ae-1147f3b2af15/public_url");
    const cloudOpsPdf = cloudOps.getByRole("link", {name: "Download AWS Certified CloudOps Engineer - Associate certificate"});
    assert.equal(await cloudOpsPdf.getAttribute("href"), "images/AWS SOA.pdf");
    assert.equal(await cloudOpsPdf.getAttribute("download"), "");
    await page.locator('[data-cert-filter="other"]').click();
    assert.equal(await page.locator(".cert-card:visible").count(), 2);
    assert.equal(await cloudOps.isVisible(), false);
    await page.locator('[data-cert-filter="all"]').click();
    assert.equal(await page.locator(".cert-card:visible").count(), 8);
    assert.equal(await cloudOps.isVisible(), true);
    await page.locator('[data-filter="cloud"]').click();
    assert.equal(await page.locator(".project-card:visible").count(), 1);
    await page.locator('[data-filter="all"]').click();
    assert.equal(await page.locator(".project-card:visible").count(), 4);
    const notes = page.locator(".project-details").first();
    assert.equal(await notes.getAttribute("open"), null);
    await notes.locator("summary").click();
    assert.equal(await notes.locator(".case-study-grid").isVisible(), true);
    await notes.locator("summary").click();
    assert.equal(await notes.locator(".case-study-grid").isVisible(), false);
    const diskarte = page.getByRole("button", {name:"Preview Diskarte PH",exact:true});
    await diskarte.click();
    assert.equal(await page.locator("#mediaDialog").isVisible(), true);
    assert.equal(await page.locator("#mediaTitle").innerText(), "Diskarte PH");
    await page.locator("#mediaContent img").evaluate(img=>img.decode());
    await page.screenshot({path:path.join(output,"project-preview-desktop.png")});
    await page.getByRole("button",{name:"Mobile screenshot",exact:true}).click();
    await page.locator("#mediaContent img").evaluate(img=>img.decode());
    assert.equal(await page.locator("#mediaContent img").evaluate(img=>img.naturalHeight>img.naturalWidth), true);
    assert.equal(await page.getByRole("button",{name:"Mobile screenshot",exact:true}).getAttribute("aria-pressed"),"true");
    await page.keyboard.press("Escape");
    assert.equal(await page.locator("#mediaDialog").isVisible(), false);
    assert.equal(await diskarte.evaluate(el=>el===document.activeElement), true);
    const hikes = await page.locator(".hike-top h3").allTextContents();
    assert.deepEqual(hikes, ["Kayapa Quadpeak","Mt. Tenglawan","Aritao Quadpeak","Mt. Ulap","Panimahawa Ridge","Mt. Mariglem","Mt. Daraitan","Mt. Pamitinan"]);
    await page.locator('#hiking').scrollIntoViewIfNeeded();
    const before = await page.locator('#hikeGrid').evaluate(el=>el.scrollLeft);
    await page.getByRole('button',{name:"Next hiking posts", exact:true}).click();
    assert.ok(await page.locator('#hikeGrid').evaluate(el=>el.scrollLeft) > before);
    await page.locator('#hikeGrid').focus();
    await page.keyboard.press("End");
    await page.waitForFunction(()=>document.querySelector('[aria-label="Next hiking posts"]').disabled);
    assert.equal(await page.getByRole("button",{name:"Next hiking posts",exact:true}).isDisabled(),true);
    await page.keyboard.press("Home");
    await page.waitForFunction(()=>document.getElementById("hikeGrid").scrollLeft===0);
    assert.equal(await page.locator('#hikeGrid').evaluate(el=>el.scrollLeft),0);
    assert.equal(instagramRequests.length,0,"Instagram must not load before a journal is opened");
    await page.getByRole("button",{name:"Preview Kayapa Quadpeak journal",exact:true}).click();
    await page.waitForFunction(()=>document.getElementById("mediaStatus").textContent.includes("unavailable"));
    assert.equal(await page.locator("#mediaSource").getAttribute("href"),"https://www.instagram.com/p/DaP4ZnNky9K/");
    await page.screenshot({path:path.join(output,"instagram-fallback.png")});
    await page.getByRole("button",{name:"Close preview",exact:true}).click();
    await page.locator('#skills').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(output,"skills-light.png")});
    await page.locator('#themeToggle').click();
    assert.equal(await page.locator("html").getAttribute("data-theme"),"dark");
    await page.reload({waitUntil:"load"});
    assert.equal(await page.locator("html").getAttribute("data-theme"),"dark","Theme persists on reload");
    await page.locator('#skills').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(output,"skills-dark.png")});
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:path.join(output,"desktop-dark.png")});
    await page.locator('#themeToggle').click();
    const overflow = [];
    for (const width of [320,360,390,640,768,900,1024,1440,1920]) {
      await page.setViewportSize({width,height:900});
      const dimensions = await page.evaluate(()=>({width:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
      if (dimensions.scroll > dimensions.width + 1) overflow.push({width,...dimensions});
      const clipped = await page.locator("h1,h2,h3,.skill-item span,.cert-dates").evaluateAll(elements=>elements.filter(el=>el.clientWidth>0&&el.scrollWidth>el.clientWidth+2).map(el=>el.textContent.trim()));
      assert.deepEqual(clipped,[],"No clipped headings or labels at " + width);
      if (width > 900) assert.equal(await page.evaluate(()=>document.querySelector('.nav-logo').getBoundingClientRect().right < document.getElementById('navLinks').getBoundingClientRect().left),true,"Navigation does not overlap at " + width);
    }
    assert.deepEqual(overflow, [], "No horizontal document overflow");
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:path.join(output,"mobile-light.png")});
    await page.locator('#navToggle').click();
    assert.equal(await page.locator('#navToggle').getAttribute("aria-expanded"),"true");
    await page.keyboard.press("Escape");
    assert.equal(await page.locator('#navToggle').getAttribute("aria-expanded"),"false");
    assert.equal(await page.locator('#navToggle').evaluate(el=>el===document.activeElement),true);
    await page.locator('#navToggle').click();
    await page.locator('#navLinks a[href="#contact"]').click();
    assert.equal(await page.locator('#navToggle').getAttribute("aria-expanded"),"false");
    await page.locator('#contactName').fill("Portfolio Test");
    await page.locator('#contactEmail').fill("invalid-address");
    assert.equal(await page.locator('#contactEmail').evaluate(el=>el.checkValidity()),false);
    await page.locator('#contactEmail').fill("test@example.com");
    assert.equal(await page.locator('#contactEmail').evaluate(el=>el.checkValidity()),true);
    await page.locator('#copyEmail').click();
    assert.equal(await page.evaluate(()=>window.copiedText),"angelojoedelossantos20@gmail.com");
    assert.equal(await page.locator('#copyEmail').getAttribute("aria-label"),"Email copied");
    await page.locator('#contactName').fill("   ");
    await page.locator('#contactMessage').fill("Validation check only; do not send.");
    await page.getByRole("button",{name:"Compose email",exact:false}).click();
    assert.equal(await page.locator('#formStatus').innerText(),"Please enter your name, email, and message.");
    await page.screenshot({path:path.join(output,"contact-mobile.png")});
    await page.evaluate(()=>document.querySelectorAll('img').forEach(img=>img.loading="eager"));
    await page.waitForFunction(()=>[...document.images].every(img=>img.complete),null,{timeout:20000}).catch(()=>{});
    const broken = await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||!i.naturalWidth).map(i=>({alt:i.alt,src:i.getAttribute("src")})));
    const buttonsWithoutNames = await page.locator("button").evaluateAll(buttons=>buttons.filter(b=>!b.getAttribute("aria-label")&&!b.textContent.trim()).map(b=>b.outerHTML));
    assert.deepEqual(buttonsWithoutNames,[],"Every button has an accessible name");
    await page.evaluate(()=>scrollTo(0,document.documentElement.scrollHeight));
    await page.waitForFunction(()=>document.querySelector('#navLinks a[aria-current="location"]')?.hash==="#contact");
    console.log(JSON.stringify({url,passed:"Themes, company disclosures, certification links, filters, screenshot dialog, keyboard controls, Instagram fallback, clipboard, form validation and nine viewport widths",errors,brokenImages:broken,screenshots:output},null,2));
    assert.deepEqual(errors, [], "No page JavaScript errors");
    assert.deepEqual(broken, [], "All portfolio images load");
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
